package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"slices"
)

const (
	schemaFile = "apis/v1/oas_schemas_gen.go"
	outputFile = "error_types_gen.go"
	schemaName = "Error"
	outputFunc = "asError"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func list() (ret []string, err error) {
	if f, e := parser.ParseFile(token.NewFileSet(), schemaFile, nil, 0); e != nil {
		err = fmt.Errorf("parse %s: %w", schemaFile, e)
	} else {
		for _, decl := range f.Decls {
			if g, ok := decl.(*ast.GenDecl); !ok {
				continue
			} else if g.Tok != token.TYPE {
				continue
			} else {
				for _, spec := range g.Specs {
					if t, ok := spec.(*ast.TypeSpec); !ok {
						continue
					} else if i, ok := t.Type.(*ast.Ident); !ok {
						continue
					} else if i.Name != schemaName {
						continue
					} else {
						ret = append(ret, t.Name.Name)
					}
				}
			}
		}
		if len(ret) == 0 {
			err = fmt.Errorf("no types derived from %s found in %s", schemaName, schemaFile)
		}
		slices.Sort(ret)
	}

	return ret, err
}

func generate() error {
	var source bytes.Buffer
	types, err := list()
	if err != nil {
		return fmt.Errorf("list types: %w", err)
	}

	fmt.Fprintln(&source, "// Copyright 2026- The sacloud/eventbus-api-go authors")
	fmt.Fprintln(&source, "// SPDX-License-Identifier: Apache-2.0")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "package eventbus")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, `import v1 "github.com/sacloud/sacloud-sdk-go/api/eventbus/apis/v1"`)
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "func %s(p any) (*v1.%s, bool) {\n", outputFunc, schemaName)
	fmt.Fprintln(&source, "\tswitch p := p.(type) {")
	for _, name := range types {
		fmt.Fprintf(&source, "\tcase *v1.%s:\n", name)
		fmt.Fprintf(&source, "\t\treturn (*v1.%s)(p), true\n", schemaName)
	}
	fmt.Fprintln(&source, "\tdefault:")
	fmt.Fprintln(&source, "\t\treturn nil, false")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "}")

	if formatted, err := format.Source(source.Bytes()); err != nil {
		return fmt.Errorf("format generated source: %w", err)
	} else if err := os.WriteFile(outputFile, formatted, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", outputFile, err)
	} else {
		return nil
	}
}
