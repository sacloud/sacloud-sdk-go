package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"slices"
)

type schema struct {
	file       string
	pkg        string
	importPath string
}

var schemas = []schema{
	{
		file:       "apis/v1/queue/oas_schemas_gen.go",
		pkg:        "queue",
		importPath: "github.com/sacloud/sacloud-sdk-go/api/simplemq/apis/v1/queue",
	},
	{
		file:       "apis/v1/message/oas_schemas_gen.go",
		pkg:        "message",
		importPath: "github.com/sacloud/sacloud-sdk-go/api/simplemq/apis/v1/message",
	},
}

const outputFile = "error_types_gen.go"

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func list(s schema) (ret []string, err error) {
	if f, e := parser.ParseFile(token.NewFileSet(), s.file, nil, 0); e != nil {
		return nil, fmt.Errorf("parse %s: %w", s.file, e)
	} else {
		for _, decl := range f.Decls {
			if g, ok := decl.(*ast.GenDecl); !ok {
				continue
			} else if g.Tok != token.TYPE {
				continue
			} else {
				for _, spec := range g.Specs {
					if t, ok := spec.(*ast.TypeSpec); !ok {
						continue
					} else if i, ok := t.Type.(*ast.Ident); !ok {
						continue
					} else if i.Name != "Error" {
						continue
					} else {
						ret = append(ret, t.Name.Name)
					}
				}
			}
		}
		if len(ret) == 0 {
			return nil, fmt.Errorf("no types derived from Error found in %s", s.file)
		}
		slices.Sort(ret)
	}
	return ret, nil
}

func generate() error {
	var source bytes.Buffer

	fmt.Fprintln(&source, "// Copyright 2026- The sacloud/simplemq-api-go authors")
	fmt.Fprintln(&source, "// SPDX-License-Identifier: Apache-2.0")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "package simplemq")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import (")
	for _, s := range schemas {
		fmt.Fprintf(&source, "\t%s %q\n", s.pkg, s.importPath)
	}
	fmt.Fprintln(&source, ")")
	for _, s := range schemas {
		fmt.Fprintln(&source)
		fmt.Fprintf(&source, "func as%sError(p any) (*%s.Error, bool) {\n", capitalize(s.pkg), s.pkg)
		fmt.Fprintln(&source, "\tswitch p := p.(type) {")
		types, err := list(s)
		if err != nil {
			return fmt.Errorf("list types: %w", err)
		}
		for _, name := range types {
			fmt.Fprintf(&source, "\tcase *%s.%s:\n", s.pkg, name)
			fmt.Fprintf(&source, "\t\treturn (*%s.Error)(p), true\n", s.pkg)
		}
		fmt.Fprintln(&source, "\tdefault:")
		fmt.Fprintln(&source, "\t\treturn nil, false")
		fmt.Fprintln(&source, "\t}")
		fmt.Fprintln(&source, "}")
	}

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(outputFile, formatted, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", outputFile, err)
	}
	return nil
}

func capitalize(s string) string {
	return string(s[0]-('a'-'A')) + s[1:]
}
