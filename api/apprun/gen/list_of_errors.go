package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"slices"
	"strings"
)

const (
	schemaFile = "apis/v1/oas_schemas_gen.go"
	outputFile = "error_types_gen.go"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	f, err := parser.ParseFile(token.NewFileSet(), schemaFile, nil, 0)
	if err != nil {
		return fmt.Errorf("parse %s: %w", schemaFile, err)
	}

	methods := make(map[string]map[string]bool)
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 {
			continue
		}
		if fn.Name.Name != "GetModelDefaultError" && fn.Name.Name != "GetModelCloudctrlError" {
			continue
		}
		receiver, ok := fn.Recv.List[0].Type.(*ast.Ident)
		if !ok {
			return fmt.Errorf("unexpected receiver for %s", fn.Name.Name)
		}
		if methods[receiver.Name] == nil {
			methods[receiver.Name] = make(map[string]bool)
		}
		methods[receiver.Name][fn.Name.Name] = true
	}
	if len(methods) == 0 {
		return fmt.Errorf("no error model types found in %s", schemaFile)
	}

	var names []string
	for name, getters := range methods {
		if !getters["GetModelDefaultError"] || !getters["GetModelCloudctrlError"] {
			return fmt.Errorf("incomplete error model getters for %s", name)
		}
		names = append(names, name)
	}
	slices.Sort(names)

	var source bytes.Buffer
	fmt.Fprintln(&source, "// Copyright 2026- The sacloud/apprun-api-go authors")
	fmt.Fprintln(&source, "// SPDX-License-Identifier: Apache-2.0")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "package apprun")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import (")
	fmt.Fprintln(&source, `"net/http"`)
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, `v1 "github.com/sacloud/sacloud-sdk-go/api/apprun/apis/v1"`)
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "func errorModelStatusCode(model modelErrorGetter) int {")
	fmt.Fprintln(&source, "switch model.(type) {")
	for _, name := range names {
		status, err := statusCode(name)
		if err != nil {
			return err
		}
		fmt.Fprintf(&source, "case v1.%s, *v1.%s:\nreturn %s\n", name, name, status)
	}
	fmt.Fprintln(&source, "default:")
	fmt.Fprintln(&source, "return 0")
	fmt.Fprintln(&source, "}")
	fmt.Fprintln(&source, "}")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(outputFile, formatted, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", outputFile, err)
	}
	return nil
}

func statusCode(name string) (string, error) {
	for _, status := range []struct {
		suffix string
		value  string
	}{
		{"BadRequest", "http.StatusBadRequest"},
		{"Unauthorized", "http.StatusUnauthorized"},
		{"Forbidden", "http.StatusForbidden"},
		{"NotFound", "http.StatusNotFound"},
		{"Conflict", "http.StatusConflict"},
		{"InternalServerError", "http.StatusInternalServerError"},
	} {
		if strings.HasSuffix(name, status.suffix) {
			return status.value, nil
		}
	}
	return "", fmt.Errorf("unknown HTTP status in error type %s", name)
}
