package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"slices"
	"strings"
)

const (
	schemaFile = "apis/v1/oas_schemas_gen.go"
	outputFile = "error_types_gen.go"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func list(path string) ([]string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}

	responses := make(map[string]bool)
	for _, decl := range f.Decls {
		method, ok := decl.(*ast.FuncDecl)
		if !ok || method.Recv == nil || !strings.HasSuffix(method.Name.Name, "Res") {
			continue
		}
		ptr, ok := method.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		if name, ok := ptr.X.(*ast.Ident); ok {
			responses[name.Name] = true
		}
	}

	var types []string
	for _, decl := range f.Decls {
		group, ok := decl.(*ast.GenDecl)
		if !ok || group.Tok != token.TYPE {
			continue
		}
		for _, spec := range group.Specs {
			t := spec.(*ast.TypeSpec)
			s, ok := t.Type.(*ast.StructType)
			if !ok || !responses[t.Name.Name] {
				continue
			}
			var isOK, message bool
			for _, field := range s.Fields.List {
				fieldType, ok := field.Type.(*ast.Ident)
				if !ok {
					continue
				}
				for _, name := range field.Names {
					isOK = isOK || name.Name == "IsOk" && fieldType.Name == "bool"
					message = message || name.Name == "Message" && fieldType.Name == "string"
				}
			}
			if isOK && message {
				types = append(types, t.Name.Name)
			}
		}
	}
	if len(types) == 0 {
		return nil, fmt.Errorf("no error response types found in %s", path)
	}
	slices.Sort(types)
	return types, nil
}

func generate() error {
	types, err := list(schemaFile)
	if err != nil {
		return fmt.Errorf("list types: %w", err)
	}
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Copyright 2026- The sacloud/workflows-api-go Authors")
	fmt.Fprintln(&source, "// SPDX-License-Identifier: Apache-2.0")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "package workflows")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import (")
	fmt.Fprintln(&source, `"net/http"`)
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, `v1 "github.com/sacloud/sacloud-sdk-go/api/workflows/apis/v1"`)
	fmt.Fprintln(&source, `"github.com/sacloud/sacloud-sdk-go/common/packages/httperror"`)
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "func asErrorResponse(p any) (errorish, int, bool) {")
	fmt.Fprintln(&source, "\tif p == nil {")
	fmt.Fprintln(&source, "\t\treturn nil, 0, false")
	fmt.Fprintln(&source, "\t} else if httperror.IsTypedNil(p) {")
	fmt.Fprintln(&source, "\t\treturn nil, 0, false")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "\tswitch p := p.(type) {")
	for _, name := range types {
		status, err := statusCode(name)
		if err != nil {
			return err
		}
		fmt.Fprintf(&source, "\tcase *v1.%s:\n\t\treturn p, %s, true\n", name, status)
	}
	fmt.Fprintln(&source, "\tdefault:")
	fmt.Fprintln(&source, "\t\treturn nil, 0, false")
	fmt.Fprintln(&source, "\t}")
	fmt.Fprintln(&source, "}")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(outputFile, formatted, 0o600); err != nil {
		return fmt.Errorf("write %s: %w", outputFile, err)
	}
	return nil
}

func statusCode(name string) (string, error) {
	for _, status := range []struct {
		suffix string
		value  string
	}{
		{"BadRequest", "http.StatusBadRequest"},
		{"Unauthorized", "http.StatusUnauthorized"},
		{"PaymentRequired", "http.StatusPaymentRequired"},
		{"Forbidden", "http.StatusForbidden"},
		{"NotFound", "http.StatusNotFound"},
		{"Conflict", "http.StatusConflict"},
		{"InternalServerError", "http.StatusInternalServerError"},
	} {
		if strings.HasSuffix(name, status.suffix) {
			return status.value, nil
		}
	}
	return "", fmt.Errorf("unknown HTTP status in error type %s", name)
}
