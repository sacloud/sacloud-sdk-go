package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"slices"
)

const (
	schemaFile = "apis/v1/oas_schemas_gen.go"
	outputFile = "error_types_gen.go"
)

func generate() error {
	bases := []string{"BadRequest", "Conflict", "Forbidden", "NotFound", "TooManyRequestsHeaders", "Unauthorized"}
	types := make(map[string][]string, len(bases))
	f, err := parser.ParseFile(token.NewFileSet(), schemaFile, nil, 0)
	if err != nil {
		return fmt.Errorf("parse %s: %w", schemaFile, err)
	}
	for _, decl := range f.Decls {
		if group, ok := decl.(*ast.GenDecl); !ok {
			continue
		} else if group.Tok != token.TYPE {
			continue
		} else {
			for _, spec := range group.Specs {
				t, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				} else if t.Assign.IsValid() {
					continue
				} else if base, ok := t.Type.(*ast.Ident); !ok {
					continue
				} else if slices.Contains(bases, base.Name) {
					types[base.Name] = append(types[base.Name], t.Name.Name)
				}
			}
		}
	}

	var source bytes.Buffer
	fmt.Fprintln(&source, "// Copyright 2026- The security-control-api-go Authors")
	fmt.Fprintln(&source, "// SPDX-License-Identifier: Apache-2.0")
	fmt.Fprintln(&source, "\n// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&source, "\npackage securitycontrol")
	fmt.Fprintln(&source, "\nimport v1 \"github.com/sacloud/sacloud-sdk-go/api/security-control/apis/v1\"")
	fmt.Fprintln(&source, "\nfunc asErrorResponse(p any) (any, bool) {")
	fmt.Fprintln(&source, "\tswitch p := p.(type) {")
	for _, base := range bases {
		if len(types[base]) == 0 {
			return fmt.Errorf("no types derived from %s found in %s", base, schemaFile)
		}
		slices.Sort(types[base])
		for _, name := range types[base] {
			fmt.Fprintf(&source, "\tcase *v1.%s:\n\t\treturn (*v1.%s)(p), true\n", name, base)
		}
	}
	fmt.Fprintln(&source, "\tdefault:\n\t\treturn nil, false\n\t}\n}")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(outputFile, formatted, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outputFile, err)
	}
	return nil
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
